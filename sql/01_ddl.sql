-- RETAIL_SALES: database, schemas, RAW landing tables.
-- Hybrid ELT: files land as-is. Business rules live in STAGING/MART.

CREATE DATABASE IF NOT EXISTS RETAIL_SALES;
USE DATABASE RETAIL_SALES;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS MART;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE COMPUTE_WH;

CREATE TABLE IF NOT EXISTS RAW.SALES_HEADER (
    SALE_ID           VARCHAR,
    SALE_DATE         VARCHAR,
    STORE_ID          VARCHAR,
    STORE_NAME        VARCHAR,
    CITY              VARCHAR,
    STATE             VARCHAR,
    REGION            VARCHAR,
    CASHIER_NAME      VARCHAR,
    PAYMENT_TYPE      VARCHAR,
    CUSTOMER_ID_RAW   VARCHAR,
    CUSTOMER_TYPE     VARCHAR,
    UPDATE_DATE       VARCHAR,
    _LOAD_DATE        DATE,
    _FILE_NAME        VARCHAR,
    _INGESTED_AT      TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW.SALES_ITEMS (
    ITEM_ID           VARCHAR,
    SALE_ID           VARCHAR,
    PRODUCT_ID        VARCHAR,
    PRODUCT_NAME      VARCHAR,
    CATEGORY          VARCHAR,
    UNIT_PRICE_USD    VARCHAR,
    QUANTITY          VARCHAR,
    DISCOUNT_PCT      VARCHAR,
    TOTAL_VALUE       VARCHAR,
    UPDATE_DATE       VARCHAR,
    _LOAD_DATE        DATE,
    _FILE_NAME        VARCHAR,
    _INGESTED_AT      TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW.CUSTOMERS (
    CUSTOMER_ID       NUMBER,
    PAYLOAD           VARIANT,
    _LOAD_DATE        DATE,
    _FILE_NAME        VARCHAR,
    _INGESTED_AT      TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW.LOAD_LOG (
    LOAD_ID           NUMBER AUTOINCREMENT,
    LOAD_DATE         DATE,
    SOURCE_NAME       VARCHAR,
    FILE_NAME         VARCHAR,
    ROW_COUNT         NUMBER,
    STATUS            VARCHAR,
    MESSAGE           VARCHAR,
    INGESTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
